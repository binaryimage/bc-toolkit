"""presetlib.py - write a plugin's built-in programs as C++ for addPrograms().
Each preset is (name, {param_key: value}); keys map to enum constants. Level trims (dB, from the
test rig) are added to the output param so every program sits near the same loudness."""
import json, os

def emit(path, presets, keymap, out_key='out', levels_path=None, out_range=(-24.0, 12.0)):
    levels = json.load(open(levels_path)) if levels_path and os.path.exists(levels_path) else {}
    names = set()
    lines = [f'// Generated by tools - {len(presets)} programs. Do not edit by hand.']
    for name, vals in presets:
        assert name not in names, 'duplicate preset name ' + name
        assert len(name) <= 22, 'name too long: ' + name
        names.add(name)
        v = dict(vals)
        if name in levels and out_key in keymap:
            v[out_key] = max(out_range[0], min(out_range[1], round(v.get(out_key, 0.0) + levels[name], 1)))
        parts = []
        for k, x in v.items():
            if k not in keymap: raise KeyError(f'{name}: unknown param {k}')
            x = float(x)
            parts.append(f'{{{keymap[k]}, {x:.4g}f}}'.replace('.0f}', '.0f}') if '.' in f'{x:.4g}' or 'e' in f'{x:.4g}' else f'{{{keymap[k]}, {x:.4g}.0f}}')
        lines.append(f'program("{name}", {{{", ".join(parts)}}});')
    open(path, 'w').write('\n'.join(lines) + '\n')
    return len(presets)
